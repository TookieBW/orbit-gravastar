//! UI strings. Every language must fill every field, so a missing translation
//! is a compile error.

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    De,
    En,
}

impl Lang {
    pub fn code(self) -> &'static str {
        match self {
            Lang::De => "de",
            Lang::En => "en",
        }
    }

    pub fn from_code(s: &str) -> Option<Lang> {
        match s {
            "de" => Some(Lang::De),
            "en" => Some(Lang::En),
            _ => None,
        }
    }

    /// German if the OS user locale is German, English otherwise.
    pub fn system() -> Lang {
        let vars = ["LANG", "LC_ALL", "LC_MESSAGES"];
        if vars.iter().filter_map(|v| std::env::var(v).ok()).any(|v| v.to_lowercase().starts_with("de")) {
            return Lang::De;
        }
        #[cfg(windows)]
        if windows_locale_is_german() {
            return Lang::De;
        }
        Lang::En
    }

    pub fn s(self) -> &'static Strings {
        match self {
            Lang::De => &DE,
            Lang::En => &EN,
        }
    }
}

#[cfg(windows)]
fn windows_locale_is_german() -> bool {
    #[link(name = "kernel32")]
    extern "system" {
        fn GetUserDefaultUILanguage() -> u16;
    }
    // Primary language id 0x07 = German.
    unsafe { GetUserDefaultUILanguage() & 0x3ff == 0x07 }
}

